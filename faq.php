        <summary>What is Warqtek?</summary>
        <p>Warqtek is a digital platform designed to simplify administrative procedures for OFPPT students, allowing them to request and receive official documents online.</p>
      </details>
      <details>
        <summary>Who can use Warqtek?</summary>
        <p>All students enrolled in OFPPT institutions can access the platform to request administrative documents.</p>
      </details>
      <details>
        <summary>What documents can I request?</summary>
        <p>You can request school certificates, transcripts, diplomas, internship attestations, scholarship applications, and other essential administrative documents.</p>
      </details>
      <details>
        <summary>How do I submit a request?</summary>
        <p>Simply log in to Warqtek, select the document you need, fill out the required information, and submit your request.</p>
      </details>
      <details>
        <summary>How long does it take to process my request?</summary>
        <p>Processing times may vary depending on the type of document, but you will be notified once your request is completed.</p>
      </details>
      <details>
        <summary>How will I receive my document?</summary>
        <p>Documents can be downloaded from the platform or picked up at your training center. You will receive a notification when your request is ready.</p>
      </details>
      <details>
        <summary>Do I need to visit my training center for verification?</summary>
        <p>Most requests are processed online, but in some cases, you may need to visit your center for additional verification.</p>
      </details>
      <details>
        <summary>What should I do if I made a mistake in my request?</summary>
        <p>If you submitted incorrect information, contact your training center as soon as possible to correct it.</p>
      </details>
      <details>
        <summary>Who do I contact if I have issues with my request?</summary>
        <p>If you encounter any issues, you can reach out to your training center&#39;s administration for assistance.</p>
